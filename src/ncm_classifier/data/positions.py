"""Official descriptions of the positions the model classifies.

The data file (positions.json) is generated by scripts/build_positions.py from
the official NCM table and shipped inside the package, so it is available
wherever the package is installed (the API container included).
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from dataclasses import dataclass
from functools import cache
from importlib.resources import files
from types import MappingProxyType


@dataclass(frozen=True)
class Position:
    code: str
    formatted: str
    description: str


@dataclass(frozen=True)
class PositionCatalog:
    ncm_table: str
    legal_act: str
    level: str
    positions: Mapping[str, Position]

    def describe(self, code: str) -> Position:
        try:
            return self.positions[code]
        except KeyError as exc:
            raise KeyError(f"position {code!r} has no official description") from exc


@cache
def load_positions() -> PositionCatalog:
    raw = json.loads(files("ncm_classifier.data").joinpath("positions.json").read_text("utf-8"))
    positions = {
        code: Position(code, item["formatted"], item["description"])
        for code, item in raw["positions"].items()
    }
    return PositionCatalog(
        raw["ncm_table"], raw["legal_act"], raw["level"], MappingProxyType(positions)
    )
